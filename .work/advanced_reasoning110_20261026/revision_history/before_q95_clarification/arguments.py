def add(n, subtype, stem, options, answer, mechanism, refs, premises, conclusion,
        link, explanations, comparison, difficulty='中高', formal=None):
    assert len(options) == len(explanations) == 4
    ask = {
        '加强': '以下哪项如果为真，最能支持上述论证？',
        '削弱': '以下哪项如果为真，最能削弱上述论证？',
        '前提': '上述论证的成立，还需要补充以下哪项作为前提？',
        '解释': '以下哪项如果为真，最能解释上述看似矛盾的现象？',
        '评价': '以下哪个问题的答案最有助于评价上述论证？',
        '归纳': '根据上述信息，可以得出以下哪项？',
    }[subtype]
    roles = []
    for i, explanation in enumerate(explanations):
        roles.append({'label': 'ABCD'[i], 'text': options[i],
                      'target_direction_strength_scope': explanation,
                      'selected': 'ABCD'[i] == answer})
    prefix = {'加强':'加强论证','削弱':'削弱论证','前提':'前提假设',
              '解释':'解释说明','评价':'论证评价','归纳':'归纳推断'}[subtype]
    q = dict(n=n, category='逻辑论证', subtype=subtype, stem=stem, ask=ask,
             options=options, answer=answer, point=f'{prefix}：{mechanism}',
             analysis=['论证主线：' + '；'.join(premises) + '。论证要得到的是：' + conclusion + '。',
                       '隐含连接：' + link] +
                      [f'{"ABCD"[i]}项：{x}' for i, x in enumerate(explanations)] +
                      ['比较：' + comparison], difficulty=difficulty,
             mechanism=mechanism, source_refs=refs,
             model={'premises': premises, 'conclusion': conclusion,
                    'implicit_link': link, 'option_roles': roles,
                    'unique_choice_rationale': comparison,
                    'formal_or_numeric_witness': formal,
                    'semantic_boundary': '自然语言选项的相关性、范围与比较强度须人工复核；结构和数值检验不能证明自然语言唯一性。'})
    QUESTIONS.append(q)
    return q


